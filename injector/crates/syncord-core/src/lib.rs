//! `syncord-core` — Discord install discovery, signed-payload verification and
//! safe injection for the Syncord Injector.
//!
//! The crate exists as a separate library rather than as part of the Tauri
//! application for one reason: **it must be testable without a GUI, a webview,
//! or a running Discord.** Everything in here is pure `std` plus four
//! well-audited crates, so `cargo test` runs in seconds in CI and the
//! security-relevant code — the part that writes into an installed application
//! — is covered by ordinary unit tests.
//!
//! ── The rule the whole crate is organised around ────────────────────────────
//!
//! **Nothing is written that has not been verified first, and a failure never
//! leaves a partial write behind.**
//!
//! In practice that means the pipeline is always
//!
//! ```text
//!   discover ──▶ extract to a staging directory ──▶ verify ──▶ atomic swap
//!                  (untrusted input, no           (signature  (one rename)
//!                   privilege)                     + digests)
//! ```
//!
//! and the steps cannot be reordered or skipped. [`inject::inject`] re-verifies
//! even when the caller already did, because the interval between "verified"
//! and "written" is where a bug would stop being a bug and start being a
//! compromised client.
//!
//! ── Cross-language contracts ────────────────────────────────────────────────
//!
//! Three things are duplicated between this crate and the TypeScript client,
//! and each duplication is a place the two could disagree:
//!
//! | What | TypeScript | Rust |
//! |---|---|---|
//! | Where Discord lives | `scripts/lib/discordInstalls.mjs` | [`discovery`] |
//! | The signed manifest bytes | `src/main/security/integrity.ts` | [`verify`] |
//! | The release key | `scripts/build.mjs` | `build.rs` |
//!
//! Divergence in the first means the CLI and the GUI target different Discord
//! installations. Divergence in the second means a genuine release is refused.
//! Both fail *closed*, and `tests/parity.rs` pins both against fixtures
//! generated by the real TypeScript, so a divergence fails the build rather
//! than reaching a user.
//!
//! Nothing in this crate is a security boundary against a *local* attacker who
//! can already run code as the user — they could patch the Injector itself. It
//! is a boundary against a *remote* one: a hostile archive, a compromised
//! mirror, and a tampered release, none of which can write to disk here.

// `unsafe` is forbidden outright: every guarantee this crate makes about where
// it writes is expressed in safe code, and a single `unsafe` block would put
// that guarantee outside the reach of the type checker.
//
// `missing_docs` is a warning rather than a deny because this project documents
// *why* a decision was made, not what a field is called. The public API is
// documented at the type and function level and on every error variant — those
// are the parts a caller has to match on. Field-level restatement is noise.
#![warn(missing_docs)]
#![deny(unsafe_code)]

pub mod access;
pub mod archive;
pub mod discovery;
pub mod inject;
pub mod release;
pub mod verify;

#[cfg(test)]
#[allow(
    clippy::expect_used,
    clippy::unwrap_used,
    reason = "a failing test should panic loudly rather than return an error"
)]
mod tests;
#[cfg(test)]
#[allow(
    clippy::expect_used,
    clippy::unwrap_used,
    reason = "test fixtures assert on specific values; a panic with a message is the assertion"
)]
mod testsupport;

