/// The Syncord version this Injector was built from.
///
/// Kept in step with `VERSION` in `src/shared/constants.ts` by hand. The
/// Injector is not the client and does not decide whether an update applies —
/// that is `evaluateUpdateOffer` in `src/shared/release.ts`, running in the
/// client — so this is for display and logging only. A mismatch is cosmetic.
pub const INJECTOR_VERSION: &str = env!("CARGO_PKG_VERSION");
